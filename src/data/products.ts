export const categories = ['Electronics', 'Fashion', 'Home & Living', 'Accessories', 'Beauty', 'Sports'];

export const getProductById = (id: string): Product | undefined =>
  products.find((p) => p.id === id);

export const getProductsByCategory = (category: string): Product[] =>
  products.filter((p) => p.category === category);

export const getFeaturedProducts = (): Product[] =>
  products.filter((p) => p.rating >= 4.6).slice(0, 8);

export const getDeals = (): Product[] =>
  products.filter((p) => p.originalPrice !== undefined).slice(0, 6);

export const getTrendingProducts = (): Product[] =>
  [...products].sort((a, b) => b.reviewCount - a.reviewCount).slice(0, 8);

export const searchProducts = (query: string, category?: string): Product[] => {
  const q = query.toLowerCase();
  return products.filter((p) => {
    const matchesQuery =
      !q ||
      p.name.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      p.tags.some((t) => t.toLowerCase().includes(q)) ||
      p.description.toLowerCase().includes(q);
    const matchesCategory = !category || p.category === category;
    return matchesQuery && matchesCategory;
  });
};
