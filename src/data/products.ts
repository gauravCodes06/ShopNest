export const getProductById = (id: string): Product | undefined =>
  products.find((p) => p.id === id);

export const getProductsByCategory = (category: string): Product[] => {
  const norm = category.toLowerCase().trim();

  return products.filter((p) => {
    const pCat = p.category.toLowerCase().trim();

    if (norm === 'all' || norm === 'all categories') return true;
    if (norm === 'mobiles' || norm === 'mobile' || norm === 'smartphones') {
      return pCat === 'mobiles';
    }
    if (norm === 'computers' || norm === 'laptops' || norm === 'computer') {
      return pCat === 'computers';
    }
    if (norm === 'mobiles, computers' || norm === 'mobiles, computers & laptops') {
      return pCat === 'mobiles' || pCat === 'computers';
    }
    if (norm === 'electronics' || norm === 'audio' || norm === 'tv, appliances, electronics') {
      return pCat === 'electronics';
    }
    if (norm === 'fashion' || norm === 'clothing' || norm === 'apparel' || norm === "men's fashion" || norm === "women's fashion") {
      return pCat === 'fashion';
    }
    if (norm === 'home & kitchen' || norm === 'home' || norm === 'kitchen' || norm === 'home, kitchen, pets' || norm === 'home & living') {
      return pCat === 'home & kitchen';
    }
    if (norm === 'beauty' || norm === 'skincare' || norm === 'beauty, health, grocery') {
      return pCat === 'beauty';
    }
    if (norm === 'sports' || norm === 'fitness' || norm === 'sports, fitness, bags, luggage') {
      return pCat === 'sports';
    }
    if (norm === 'books' || norm === 'book') {
      return pCat === 'books';
    }
    return pCat === norm;
  });
};

export const getFeaturedProducts = (): Product[] =>
  products.filter((p) => p.rating >= 4.7).slice(0, 8);

export const getDeals = (): Product[] =>
  products.filter((p) => p.originalPrice !== undefined && p.originalPrice > p.price);

export const getTrendingProducts = (): Product[] =>
  [...products].sort((a, b) => b.reviewCount - a.reviewCount).slice(0, 8);

export const searchProducts = (query: string, category?: string): Product[] => {
  const q = query.toLowerCase().trim();

  // If query is empty, filter purely by category
  if (!q) {
    if (category && category !== 'All' && category !== 'All Categories') {
      return getProductsByCategory(category);
    }
    return products;
  }

  // Special shortcuts
  if (
    q === 'deal' ||
    q === 'deals' ||
    q === 'best deals' ||
    q === "today's best deals" ||
    q === 'discount' ||
    q === 'offers'
  ) {
    let deals = getDeals();
    if (category && category !== 'All' && category !== 'All Categories') {
      const catNorm = category.toLowerCase().trim();
      deals = deals.filter(p => p.category.toLowerCase().trim() === catNorm);
    }
    return deals;
  }

  if (
    q === 'best seller' ||
    q === 'bestseller' ||
    q === 'bestsellers' ||
    q === 'top rated' ||
    q === 'bestsellers & top rated' ||
    q === 'best-seller'
  ) {
    let sorted = [...products].sort((a, b) => b.rating - a.rating || b.reviewCount - a.reviewCount);
    if (category && category !== 'All' && category !== 'All Categories') {
      const catNorm = category.toLowerCase().trim();
      sorted = sorted.filter(p => p.category.toLowerCase().trim() === catNorm);
    }
    return sorted;
  }

  const queryWords = q.split(/\s+/).filter(w => w.length > 1);

  // Score each product for precision and ranking
  const scored = products.map((p) => {
    const pName = p.name.toLowerCase();
    const pCat = p.category.toLowerCase();
    const pDesc = p.description.toLowerCase();
    const pTags = p.tags.map((t) => t.toLowerCase());

    // Check category restriction strictly if provided
    if (category && category !== 'All' && category !== 'All Categories') {
      const catNorm = category.toLowerCase().trim();
      let matchesCat = false;
      if (catNorm === 'mobiles' || catNorm === 'mobile' || catNorm === 'smartphones') {
        matchesCat = pCat === 'mobiles';
      } else if (catNorm === 'computers' || catNorm === 'laptops' || catNorm === 'computer') {
        matchesCat = pCat === 'computers';
      } else if (catNorm === 'mobiles, computers') {
        matchesCat = pCat === 'mobiles' || pCat === 'computers';
      } else if (catNorm === 'electronics' || catNorm === 'audio' || catNorm === 'tv, appliances, electronics') {
        matchesCat = pCat === 'electronics';
      } else if (catNorm === 'fashion' || catNorm === 'clothing' || catNorm === "men's fashion" || catNorm === "women's fashion") {
        matchesCat = pCat === 'fashion';
      } else if (catNorm === 'home & kitchen' || catNorm === 'home' || catNorm === 'kitchen' || catNorm === 'home, kitchen, pets') {
        matchesCat = pCat === 'home & kitchen';
      } else if (catNorm === 'beauty' || catNorm === 'beauty, health, grocery') {
        matchesCat = pCat === 'beauty';
      } else if (catNorm === 'sports' || catNorm === 'sports, fitness, bags, luggage') {
        matchesCat = pCat === 'sports';
      } else if (catNorm === 'books') {
        matchesCat = pCat === 'books';
      } else {
        matchesCat = pCat === catNorm || pCat.includes(catNorm);
      }

      if (!matchesCat) {
        return { product: p, score: 0 };
      }
    }

    let score = 0;

    // Full query matches
    if (pName === q) score += 200;
    else if (pName.includes(q)) score += 100;
    if (pCat === q) score += 80;
    else if (pCat.includes(q)) score += 50;
    if (pTags.includes(q)) score += 60;
    if (pDesc.includes(q)) score += 10;

    // Word level matches with exact word boundaries
    for (const word of queryWords) {
      const wordStem = word.replace(/s$/, '');
      const nameWords = pName.split(/[^a-z0-9]+/);
      const isWordInName = nameWords.some(w => w === word || (wordStem.length > 2 && w === wordStem));
      const isWordInCat = pCat.split(/[^a-z0-9]+/).some(w => w === word || (wordStem.length > 2 && w === wordStem));
      const isWordInTags = pTags.some(t => t === word || t === wordStem || t.split(/[^a-z0-9]+/).some(w => w === word || (wordStem.length > 2 && w === wordStem)));
      const isWordInDesc = new RegExp(`\\b${word}\\b`, 'i').test(pDesc);

      if (isWordInCat) score += 60;
      if (isWordInName) score += 40;
      if (isWordInTags) score += 30;
      if (isWordInDesc) score += 5;
    }

    // Direct category intent: if query asks for "mobile", "phone", "laptop", "book" prioritize that department
    if (['mobile', 'phone', 'smartphone'].some(w => q.includes(w)) && pCat === 'mobiles') {
      score += 150;
    }
    if (['laptop', 'computer', 'pc', 'macbook'].some(w => q.includes(w)) && pCat === 'computers') {
      score += 150;
    }
    if (['headphone', 'earbud', 'speaker', 'audio', 'tv'].some(w => q.includes(w)) && pCat === 'electronics') {
      score += 150;
    }
    if (['shirt', 'dress', 'kurti', 'sneaker', 'clothing', 'fashion'].some(w => q.includes(w)) && pCat === 'fashion') {
      score += 150;
    }
    if (['cookware', 'kitchen', 'blender', 'bedsheet', 'home'].some(w => q.includes(w)) && pCat === 'home & kitchen') {
      score += 150;
    }
    if (['mascara', 'lipstick', 'skincare', 'beauty', 'makeup'].some(w => q.includes(w)) && pCat === 'beauty') {
      score += 150;
    }
    if (['cricket', 'basketball', 'football', 'badminton', 'sports'].some(w => q.includes(w)) && pCat === 'sports') {
      score += 150;
    }
    if (['book', 'novel', 'read', 'author'].some(w => q.includes(w)) && pCat === 'books') {
      score += 150;
    }

    return { product: p, score };
  });

  return scored
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score || b.product.rating - a.product.rating)
    .map((item) => item.product);
};
